let idioma = 'es';

export const idiomaActual = () => idioma;
// Para formatear números y fechas
export const localeActual = () => (idioma === 'es' ? 'es' : 'en');

export function t(clave, ...args) {
  const valor = TEXTOS[idioma][clave] ?? TEXTOS.es[clave];
  if (valor === undefined) {
    console.warn('Texto sin traducir:', clave);
    return clave;
  }
  return typeof valor === 'function' ? valor(...args) : valor;
}

// 'auto': castellano si el sistema está en castellano; si no, inglés
export function resolverIdioma(preferencia) {
  if (preferencia === 'es' || preferencia === 'en') return preferencia;
  const idiomas = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  return idiomas[0].toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function ponerIdioma(nuevo) {
  idioma = nuevo;
  document.documentElement.lang = nuevo;
  traducirPagina();
}

// Textos fijos del HTML marcados con data-t*. «clave|x» pasa x a la función
// del texto (por ejemplo data-t-title="tecla|R" → «Tecla R»).
const traducir = (marca) => t(...marca.split('|'));

export function traducirPagina(raiz = document) {
  for (const el of raiz.querySelectorAll('[data-t]')) el.textContent = traducir(el.dataset.t);
  for (const el of raiz.querySelectorAll('[data-t-html]')) el.innerHTML = traducir(el.dataset.tHtml);
  for (const el of raiz.querySelectorAll('[data-t-title]')) el.title = traducir(el.dataset.tTitle);
  for (const el of raiz.querySelectorAll('[data-t-aria]')) el.setAttribute('aria-label', traducir(el.dataset.tAria));
}
